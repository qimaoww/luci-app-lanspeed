#!/usr/bin/env node
'use strict';

// Generate a small offline registry from pinned IEEE exports. Keep original
// registrant names; OpenClash's brand-only indices are not registry evidence.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'applications/luci-app-lanspeed/htdocs/luci-static/resources/lanspeed');
const ref = process.argv[2];
if (!/^[a-f0-9]{40}$/.test(ref || '')) {
	console.error('Usage: node scripts/update-lanspeed-vendor-seed.js <runZeroInc/mac-tracker commit SHA>');
	process.exit(1);
}
const baseclass = {extend: value => value};
const names = new Function('baseclass', fs.readFileSync(path.join(dir, 'vendorNames.js'), 'utf8'))(baseclass);
const db = new Function('baseclass', fs.readFileSync(path.join(dir, 'vendorDatabase.js'), 'utf8'))(baseclass);

async function main() {
	const sources = [];
	const records = new Map();
	for (const source of db.sources.filter(s => s.format === 'csv')) {
		const url = source.urls[0].replace('/main/', '/' + ref + '/');
		const response = await fetch(url, {signal: AbortSignal.timeout(60000)});
		if (!response.ok) throw new Error('Registry download failed: ' + response.status);
		const text = await response.text();
		const parsed = db.parse(text, source);
		sources.push({id: source.id, url, sha256: crypto.createHash('sha256').update(text).digest('hex')});
		for (let i = 0; i < parsed.length; i += 3) {
			const [prefix, bits, vendor] = parsed.slice(i, i + 3);
			if (!names.resolve(vendor)) continue;
			const key = bits + ':' + prefix;
			if (records.has(key) && records.get(key) !== vendor) throw new Error('Ambiguous registry prefix');
			records.set(key, vendor);
		}
	}
	const registrants = [...new Set(records.values())].sort();
	const tables = {};
	for (const bits of [36, 28, 24]) {
		const keys = [...records.keys()].filter(k => k.startsWith(bits + ':')).sort();
		tables[bits] = {p: keys.map(k => k.split(':')[1]).join(''),
			v: keys.map(k => registrants.indexOf(records.get(k)))};
	}
	if (records.size < 3000) throw new Error('Offline registry unexpectedly small');
	const meta = {revision: ref, sources, count: records.size};
	const generated = `'use strict';\n'require baseclass';\n\n` +
		`/* Generated by scripts/update-lanspeed-vendor-seed.js.\n` +
		` * Pinned IEEE MA-L/MA-M/MA-S/IAB snapshots; exact known registrant aliases only.\n` +
		` * Offline fallback, never a claim that this is the latest online registry. */\n` +
		`var META = ${JSON.stringify(meta)};\nvar NAMES = ${JSON.stringify(registrants)};\n` +
		Object.entries(tables).map(([bits, table]) => `var T${bits} = ${JSON.stringify(table)};`).join('\n') +
		`\nvar TABLES = {24:T24,28:T28,36:T36};\n\n` +
		`function lookup(mac, bits) {\n` +
		`\tif (!/^[0-9a-f]{12}$/.test(mac) || !TABLES[bits]) return null;\n` +
		`\tvar table = TABLES[bits], size = bits / 4, key = mac.slice(0, size);\n` +
		`\tvar lo = 0, hi = table.v.length - 1;\n` +
		`\twhile (lo <= hi) {\n` +
		`\t\tvar mid = (lo + hi) >>> 1, prefix = table.p.slice(mid * size, (mid + 1) * size);\n` +
		`\t\tif (prefix === key) return NAMES[table.v[mid]];\n` +
		`\t\tif (prefix < key) lo = mid + 1; else hi = mid - 1;\n` +
		`\t}\n\treturn null;\n}\n\nreturn baseclass.extend({lookup:lookup, metadata:META});\n`;
	fs.writeFileSync(path.join(dir, 'vendorSeed.js'), generated);
	console.log('Offline registry:', records.size, 'prefixes,', registrants.length, 'registrants,', Buffer.byteLength(generated), 'bytes');
}
main().catch(error => {console.error(error.message); process.exitCode = 1;});
